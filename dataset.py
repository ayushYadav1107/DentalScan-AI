def cmd_folds(args: argparse.Namespace) -> int:
    folds = build_cv_folds(args.image_dirs, n_folds=args.folds, seed=args.seed)
    yaml_paths = write_fold_configs(folds, args.out_dir, eval_roots=args.eval_dirs)

    headers = ["Fold", "Images", "Source radiographs", *CLASS_NAMES]
    rows = []
    for i, fold in enumerate(folds):
        counter: Counter[int] = Counter()
        for image_path in fold:
            for cls, *_ in read_label_file(find_label_path(image_path)):
                counter[cls] += 1
        rows.append([i, len(fold), len({source_id(p) for p in fold}),
                     *[counter.get(j, 0) for j in range(len(CLASS_NAMES))]])
    print(markdown_table(headers, rows))

    empty = [(i, CLASS_NAMES[j]) for i, row in enumerate(rows)
             for j in range(len(CLASS_NAMES)) if row[3 + j] == 0]
    if empty:
        print("\nFolds with a class entirely absent (that fold cannot score that class):")
        for fold_index, name in empty:
            print(f"  fold {fold_index}: {name}")
        print("Consider fewer folds, or merge the rarest class into a coarser label.")

    print(f"\nWrote {len(yaml_paths)} fold configs to {args.out_dir}")
    return 0


# --------------------------------------------------------------------------- #

def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("prepare", help="locate the dataset and write configs/data.yaml")
    p.add_argument("--search-root", type=Path, default=ROOT)
    p.add_argument("--dataset-root", type=Path, default=None,
                   help="Skip the search and use this directory directly.")
    p.add_argument("--out", type=Path, default=CONFIG_DIR / "data.yaml")
    p.add_argument("--also-single-copy", action="store_true",
                   help="Also write configs/data_single_copy.yaml, keeping one "
                        "offline-augmented copy per source radiograph. Pairing it "
                        "against the full list isolates what the 3x offline "
                        "augmentation contributes on top of online augmentation.")
    p.set_defaults(func=cmd_prepare)

    p = sub.add_parser("audit", help="per-class support, leakage check, imbalance")
    p.add_argument("--dataset-root", type=Path, required=True)
    p.add_argument("--out", type=Path, default=RESULTS_DIR / "dataset_audit.json")
    p.add_argument("--figure", type=Path, default=FIGURE_DIR / "class_support.png")
    p.add_argument("--no-figure", action="store_true")
    p.set_defaults(func=cmd_audit)

    p = sub.add_parser("folds", help="build grouped, rarity-aware k-fold CV splits")
    p.add_argument("--image-dirs", type=Path, nargs="+", required=True)
    p.add_argument("--eval-dirs", type=Path, nargs="*", default=None,
                   help="Validate only on images under these directories (e.g. the "
                        "231 original radiographs), while still training on the "
                        "augmented copies in the other folds.")
    p.add_argument("--folds", type=int, default=5)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out-dir", type=Path, default=CONFIG_DIR / "cv")
    p.set_defaults(func=cmd_folds)

    return parser


def main() -> int:
    args = build_parser().parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
