# audit
# --------------------------------------------------------------------------- #

def cmd_audit(args: argparse.Namespace) -> int:
    audit = audit_dataset(args.dataset_root)

    headers = ["Split", "Images", "Source radiographs", "Aug. factor", "Boxes", *CLASS_NAMES]
    rows = []
    for name, stats in audit["splits"].items():
        factor = (stats["n_images"] / stats["n_source_images"]
                  if stats["n_source_images"] else 0)
        rows.append([
            name, stats["n_images"], stats["n_source_images"], f"{factor:.1f}x",
            stats["n_boxes"], *[stats["boxes_per_class"][c] for c in CLASS_NAMES],
        ])
    table = markdown_table(headers, rows)
    print(table)

    print("\nSource-radiograph overlap between splits (must be 0):")
    for pair, count in audit["leakage"].items():
        print(f"  {pair:20s} {count:4d}  [{'OK' if count == 0 else 'LEAKAGE'}]")
    if audit["train_imbalance_ratio"]:
        print(f"\nTraining imbalance (most:least frequent class): "
              f"{audit['train_imbalance_ratio']:.0f}:1")

    if audit["warnings"]:
        print("\nWarnings:")
        for warning in audit["warnings"]:
            print(f"  - {warning}")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    audit["markdown_table"] = table
    args.out.write_text(json.dumps(audit, indent=2))
    print(f"\nWrote {args.out}")

    if not args.no_figure:
        from dentalscan.viz import plot_class_support
        counts = {n: s["boxes_per_class"] for n, s in audit["splits"].items()}
        print(f"Wrote {plot_class_support(counts, args.figure)}")
    return 0


