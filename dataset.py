#!/usr/bin/env python3
"""Dataset preparation, auditing and split construction.

Three subcommands:

    python dataset.py prepare --search-root .          # write configs/data.yaml
    python dataset.py audit   --dataset-root <path>    # support, leakage, imbalance
    python dataset.py folds   --image-dirs <...>       # grouped k-fold CV splits

``audit`` is the one to run first on any new data. It reports how many instances
of each class exist in each split, verifies that no source radiograph straddles a
split boundary, and refuses to let a class with three instances pass silently as
if it were measurable.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

from dentalscan.constants import CLASS_NAMES, CONFIG_DIR, FIGURE_DIR, RESULTS_DIR, ROOT
from dentalscan.data import (
    audit_dataset, build_cv_folds, find_label_path, list_images,
    read_label_file, source_id, write_fold_configs,
)
from dentalscan.report import markdown_table

SPLIT_ALIASES = {
    "train": ("train", "training"),
    "val": ("valid", "val", "validation"),
    "test": ("test", "testing"),
}


# --------------------------------------------------------------------------- #
# prepare
# --------------------------------------------------------------------------- #

def find_dataset_root(search_root: Path) -> Path | None:
    """Find a directory containing train/valid(-ish)/test image folders.

    The public download nests the splits several directories deep behind names
    containing spaces and parentheses - exactly the sort of path that gets
    hard-coded once and breaks for the next person. Searching for the layout is
    more robust than remembering it.
    """
    candidates: list[tuple[int, Path]] = []
    for directory in search_root.rglob("*"):
        if not directory.is_dir():
            continue
        if any(part in {".git", ".venv", "node_modules", "__pycache__"}
               for part in directory.parts):
            continue
        found = sum(
            any((directory / alias / "images").is_dir() for alias in aliases)
            for aliases in SPLIT_ALIASES.values()
        )
        if found >= 2:
            candidates.append((found, directory))
    if not candidates:
        return None
    candidates.sort(key=lambda pair: (-pair[0], len(pair[1].parts)))
    return candidates[0][1]


def resolve_split(dataset_root: Path, split: str) -> Path | None:
    for alias in SPLIT_ALIASES[split]:
        path = dataset_root / alias / "images"
        if path.is_dir():
            return path
    return None


def cmd_prepare(args: argparse.Namespace) -> int:
    dataset_root = args.dataset_root or find_dataset_root(args.search_root)
    if dataset_root is None:
        print(f"Could not find a train/valid/test layout under {args.search_root}.\n"
              "Download the dataset from https://data.mendeley.com/datasets/c4hhrkxytw/4 "
              "and pass --dataset-root explicitly.", file=sys.stderr)
        return 1

    splits = {name: resolve_split(dataset_root, name) for name in SPLIT_ALIASES}
    missing = [name for name, path in splits.items() if path is None]
    if "train" in missing or "val" in missing:
        print(f"Found {dataset_root} but it is missing: {missing}", file=sys.stderr)
        return 1

    lines = [
        "# Auto-generated by `python dataset.py prepare` - re-run after moving the data.",
        f"path: {dataset_root.resolve().as_posix()}",
    ]
    for name in ("train", "val", "test"):
        if splits[name] is not None:
            lines.append(f"{name}: {splits[name].resolve().as_posix()}")
    lines += ["", "names:"]
    lines += [f"  {i}: {n}" for i, n in enumerate(CLASS_NAMES)]
    lines.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines))

    print(f"Dataset root : {dataset_root}")
    for name in ("train", "val", "test"):
        print(f"  {name:5s}     : {splits[name] if splits[name] else 'MISSING'}")
    print(f"Wrote        : {args.out}")

    if args.also_single_copy:
        seen: set[str] = set()
        kept: list[Path] = []
        for image_path in list_images(splits["train"]):
            sid = source_id(image_path)
            if sid not in seen:
                seen.add(sid)
                kept.append(image_path)

        train_txt = args.out.parent / "train_single_copy.txt"
        train_txt.write_text("\n".join(str(p.resolve()) for p in kept) + "\n")

        single = [
            "# Auto-generated by `python dataset.py prepare --also-single-copy`.",
            "# One offline-augmented copy per source radiograph; same val/test.",
            f"path: {dataset_root.resolve().as_posix()}",
            f"train: {train_txt.resolve().as_posix()}",
        ]
        for name in ("val", "test"):
            if splits[name] is not None:
                single.append(f"{name}: {splits[name].resolve().as_posix()}")
        single += ["", "names:"]
        single += [f"  {i}: {n}" for i, n in enumerate(CLASS_NAMES)]
        single.append("")
        single_out = args.out.parent / "data_single_copy.yaml"
        single_out.write_text("\n".join(single))
        print(f"Single-copy  : {single_out}  ({len(kept)} training images, "
              f"down from {len(list_images(splits['train']))})")
    return 0


